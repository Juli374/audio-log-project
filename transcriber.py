# Known Whisper hallucinations — short phrases the model emits on silence,
# noise, or very quiet audio because its training set was dominated by
# YouTube subtitle files. Whisper-large-v3 produces these on ~99.97% of
# non-speech input (Calm-Whisper paper, arXiv 2505.12969).
#
# Patterns come from the Russian community hallucination list
# (https://gist.github.com/waveletdeboshir/8bf52f04bf78018194f25b2390c08309,
# generated by feeding 13 hours of pure noise through whisper-large-v2) and
# from openai/whisper discussions #1873, #2131.
_HALLUCINATION_PATTERNS = [
    # Russian — subtitle credits
    r"редактор\s+субтитров",
    r"корректор\s+\w\.\s*\w+",
    r"субтитры\s+(сделал|делал|выполнил|сделаны|добавил|подогнал|подготовил)",
    r"DimaTorzok",
    # Russian — YouTube outro filler
    r"спасибо\s+за\s+(про)?смотр",
    r"подписывайтесь\s+на\s+(канал|нас)",
    r"подпишись",
    r"ставьте\s+лайк",
    r"всем\s+пока",
    r"до\s+новых\s+встреч",
    r"поддержите\s+канал",
    r"смотрите\s+продолжение",
    r"продолжение\s+следует",
    # English — Whisper sometimes guesses the wrong source language on noise
    r"thank(?:s|\s+you)?\s+for\s+watching",
    r"(don't\s+forget\s+to\s+|please\s+)?(like\s+and\s+)?subscribe",
    r"translated?\s+by\s+\w+",
    # Subtitle source credits (all languages)
    r"amara\.org",
    r"castingwords",
]
_HALLUCINATION_RE = re.compile(
    "|".join(_HALLUCINATION_PATTERNS), re.IGNORECASE
)

# A transcript is treated as a hallucination only when the sum of all
# matched pattern lengths covers ≥ this fraction of it. Summing handles
# compound credits like "Субтитры сделал DimaTorzok" (two patterns match,
# together they cover ~100%). A long legitimate dictation that ends with
# «подписывайтесь на канал компании» has a single match diluted to well
# under the threshold and is NOT dropped.
_HALLUCINATION_COVERAGE = 0.65


def _is_hallucination(text: str) -> bool:
    """True if `text` is mostly a known Whisper hallucination."""
    if not text:
        return False
    total_matched = sum(
        len(m.group()) for m in _HALLUCINATION_RE.finditer(text)
    )
    if total_matched == 0:
        return False
    return total_matched / len(text) >= _HALLUCINATION_COVERAGE


_TRANSCRIPTION_TIMEOUT = 30  # seconds


class BaseTranscriber:
    def __init__(self, config: Config) -> None:
        self._config = config

    def load_model(self) -> None:
        raise NotImplementedError

    def _transcribe_raw(self, audio: np.ndarray) -> str:
        """Transcribe audio in source language (no translation)."""
        raise NotImplementedError

    def transcribe(self, audio: np.ndarray, *,
                   apply_cleanup: bool = True) -> str:
        """Transcribe + optionally clean up + optionally translate via Claude.

        We never use Whisper's built-in translate — it's unreliable on
        conversational audio and often mixes source+target languages.
        Instead we always transcribe in source language, then post-translate
        via Claude if config.target_language is set and differs from source.

        If config.cleanup_mode is enabled and apply_cleanup is True, the raw
        transcript is first sent to Claude for punctuation/capitalization
        cleanup (strict prompt — does not change content).
        """
        text = self._transcribe_raw(audio)
        if _is_hallucination(text):
            log.warning("Filtered Whisper hallucination: %.80s", text)
            return ""
        if not text:
            return text
        mode = self._config.cleanup_mode
        if (apply_cleanup
                and mode in ("light", "aggressive")
                and self._config.anthropic_api_key):
            raw = text
            try:
                text = _cleanup_via_claude(text, mode, self._config)
            except Exception:
                log.warning("Claude cleanup failed — using raw text",
                            exc_info=True)
            else:
                if text == raw:
                    log.info("Cleanup unchanged (%s): %s", mode, raw)
                else:
                    log.info("Cleanup BEFORE (%s): %s", mode, raw)
                    log.info("Cleanup AFTER  (%s): %s", mode, text)
        target = (self._config.target_language or "").strip().lower()
        if not target or target == self._config.language:
            return text
        try:
            translated = _translate_via_claude(text, target, self._config)
        except Exception:
            log.warning("Claude translation failed — returning source text",
                        exc_info=True)
            return text
        log.info("Translated → %s: %.80s…", target, translated)
        return translated


class APITranscriber(BaseTranscriber):
    def load_model(self) -> None:
        # No-op — no model to load, 0 MB RAM
        log.info("API mode — no local model to load")

    def _transcribe_raw(self, audio: np.ndarray) -> str:
        if len(audio) == 0:
            return ""

        duration = len(audio) / self._config.sample_rate
        if duration < self._config.min_duration:
            log.warning("Audio too short (%.2fs < %.2fs), skipping",
                        duration, self._config.min_duration)
            return ""

        api_key = self._config.openai_api_key
        if not api_key:
            raise RuntimeError("OpenAI API key not configured")

        # Encode audio (OGG Opus if ffmpeg available, else WAV)
        audio_bytes, filename, content_type = _encode_audio(
            audio, self._config.sample_rate)

        # Always transcribe in source language — translation happens
        # post-hoc via Claude (see BaseTranscriber.transcribe).
        boundary = "----AudioLogBoundary"
        endpoint = "https://api.openai.com/v1/audio/transcriptions"
        fields = {
            "model": self._config.openai_model,
            "file": (filename, audio_bytes, content_type),
            "language": self._config.language,
        }
        body = _build_multipart(boundary, fields)

        req = urllib.request.Request(
            endpoint,
            data=body,
            headers={
                "Authorization": f"Bearer {api_key}",
                "Content-Type": f"multipart/form-data; boundary={boundary}",
            },
            method="POST",
        )

        try:
            with urllib.request.urlopen(req, timeout=_TRANSCRIPTION_TIMEOUT) as resp:
                data = json.loads(resp.read().decode())
                text = data.get("text", "").strip()
        except urllib.error.HTTPError as e:
            body_text = e.read().decode(errors="replace")
            log.error("OpenAI API error %d: %s", e.code, body_text)
            raise RuntimeError(f"OpenAI API error {e.code}") from e

        log.info("Transcribed (API): %.80s…", text)
        return text


