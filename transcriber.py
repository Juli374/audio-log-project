def _cleanup_via_claude(text: str, mode: str, config: Config) -> str:
    """Clean up raw transcript via Claude.

    mode:
    - "light": strict — punctuation, capitalization, obvious errors only.
    - "aggressive": editor-style — replaces context-mismatched words,
      fixes grammar, may restructure minimally.

    Defenses against prompt injection (per Anthropic best practices):
    - Input is wrapped in <transcript>...</transcript> XML tags so Claude
      treats it as data, not instructions. Imperatives in dictation
      ("переправь", "сделай") would otherwise trigger conversational drift.
    - Assistant turn is prefilled with "<cleaned_transcript>" to lock the
      response format before the model can drift into a chat reply.
    - stop_sequences cuts the response at the closing tag.
    - System prompt includes few-shot examples covering imperative-heavy
      and question-heavy inputs that triggered injection in production.

    Raises on any failure — caller decides fallback behavior
    (BaseTranscriber.transcribe falls back to raw text)."""
    api_key = config.anthropic_api_key
    if not api_key:
        raise RuntimeError("Anthropic API key not configured")

    system = (_CLEANUP_AGGRESSIVE_SYSTEM_PROMPT if mode == "aggressive"
              else _CLEANUP_SYSTEM_PROMPT)
    payload = {
        "model": config.anthropic_model,
        "max_tokens": 2048,
        "temperature": 0,
        "system": system,
        "stop_sequences": ["</cleaned_transcript>"],
        "messages": [
            {"role": "user",
             "content": f"<transcript>{text}</transcript>"},
            {"role": "assistant",
             "content": "<cleaned_transcript>"},
        ],
    }
    body = json.dumps(payload).encode("utf-8")

    req = urllib.request.Request(
        "https://api.anthropic.com/v1/messages",
        data=body,
        headers={
            "x-api-key": api_key,
            "anthropic-version": "2023-06-01",
            "content-type": "application/json",
        },
        method="POST",
    )

    t0 = time.monotonic()
    try:
        with urllib.request.urlopen(req, timeout=_CLAUDE_TIMEOUT) as resp:
            data = json.loads(resp.read().decode())
    except urllib.error.HTTPError as e:
        body_text = e.read().decode(errors="replace")
        log.error("Claude cleanup error %d: %s", e.code, body_text)
        raise RuntimeError(f"Claude cleanup error {e.code}") from e

    elapsed = time.monotonic() - t0
    blocks = data.get("content", [])
    out = "".join(
        b.get("text", "") for b in blocks if b.get("type") == "text"
    )
    # Defensive: strip any stray tag echo or whitespace. The prefill
    # is NOT echoed in the response, but be paranoid in case the
    # model emits literal tags inside its output.
    out = out.replace("<cleaned_transcript>", "")
    out = out.replace("</cleaned_transcript>", "")
    out = out.strip()
    log.info("Claude cleanup: %.2fs", elapsed)
    return out or text  # if Claude returned empty, fall back to raw


