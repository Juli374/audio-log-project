def _encode_audio(audio: np.ndarray, sample_rate: int) -> tuple[bytes, str, str]:
    """Encode audio to OGG Opus for long recordings, WAV for short ones.
    ffmpeg subprocess overhead (~200ms) isn't worth it for short clips."""
    duration = len(audio) / sample_rate
    if duration >= 15.0:
        try:
            return _numpy_to_ogg_opus(audio, sample_rate), "audio.ogg", "audio/ogg"
        except Exception:
            pass
    return _numpy_to_wav(audio, sample_rate), "audio.wav", "audio/wav"


def _numpy_to_ogg_opus(audio: np.ndarray, sample_rate: int) -> bytes:
    """Convert float32 numpy array to OGG Opus via ffmpeg subprocess."""
    import subprocess
    wav_bytes = _numpy_to_wav(audio, sample_rate)
    result = subprocess.run(
        ["ffmpeg", "-i", "pipe:0", "-c:a", "libopus", "-b:a", "32k",
         "-f", "ogg", "pipe:1"],
        input=wav_bytes,
        capture_output=True,
        timeout=10,
    )
    if result.returncode != 0:
        raise RuntimeError(f"ffmpeg failed: {result.stderr.decode(errors='replace')[:200]}")
    return result.stdout


def _numpy_to_wav(audio: np.ndarray, sample_rate: int) -> bytes:
    """Convert float32 numpy array to WAV bytes (16-bit PCM)."""
    # Clip and convert to int16
    audio_clipped = np.clip(audio, -1.0, 1.0)
    pcm = (audio_clipped * 32767).astype(np.int16)
    pcm_bytes = pcm.tobytes()

    buf = io.BytesIO()
    # WAV header
    num_samples = len(pcm)
    data_size = num_samples * 2  # 16-bit = 2 bytes per sample
    buf.write(b"RIFF")
    buf.write(struct.pack("<I", 36 + data_size))
    buf.write(b"WAVE")
    buf.write(b"fmt ")
    buf.write(struct.pack("<I", 16))        # chunk size
    buf.write(struct.pack("<H", 1))         # PCM format
    buf.write(struct.pack("<H", 1))         # mono
    buf.write(struct.pack("<I", sample_rate))
    buf.write(struct.pack("<I", sample_rate * 2))  # byte rate
    buf.write(struct.pack("<H", 2))         # block align
    buf.write(struct.pack("<H", 16))        # bits per sample
    buf.write(b"data")
    buf.write(struct.pack("<I", data_size))
    buf.write(pcm_bytes)

    return buf.getvalue()


def _build_multipart(boundary: str, fields: dict) -> bytes:
    """Build multipart/form-data body.
    Values can be strings or tuples (filename, bytes, content_type)."""
    parts = []
    for key, value in fields.items():
        if isinstance(value, tuple):
            filename, data, content_type = value
            parts.append(
                f"--{boundary}\r\n"
                f'Content-Disposition: form-data; name="{key}"; filename="{filename}"\r\n'
                f"Content-Type: {content_type}\r\n\r\n"
            )
            parts.append(data)
            parts.append(b"\r\n")
        else:
            parts.append(
                f"--{boundary}\r\n"
                f'Content-Disposition: form-data; name="{key}"\r\n\r\n'
                f"{value}\r\n"
            )
    parts.append(f"--{boundary}--\r\n")

    result = b""
    for part in parts:
        if isinstance(part, str):
            result += part.encode("utf-8")
        else:
            result += part
    return result
